CREATE OR ALTER VIEW hubv.arch_permit AS
SELECT CAST(NULLIF(LTRIM(RTRIM([관리_허가대장_PK])), N'') AS VARCHAR(50)) AS [mgm_pmsrgst_pk],
       CASE WHEN LEN(NULLIF(LTRIM(RTRIM([시군구_코드])), N'')) = 5 AND LEN(NULLIF(LTRIM(RTRIM([법정동_코드])), N'')) = 5 AND (NULLIF(LTRIM(RTRIM([번])), N'') IS NULL OR TRY_CAST(NULLIF(LTRIM(RTRIM([번])), N'') AS INT) IS NOT NULL) AND (NULLIF(LTRIM(RTRIM([지])), N'') IS NULL OR TRY_CAST(NULLIF(LTRIM(RTRIM([지])), N'') AS INT) IS NOT NULL) THEN CAST(NULLIF(LTRIM(RTRIM([시군구_코드])), N'') + NULLIF(LTRIM(RTRIM([법정동_코드])), N'') + CASE LTRIM(RTRIM(ISNULL([대지_구분_코드], N'0'))) WHEN N'1' THEN N'2' ELSE N'1' END + RIGHT(N'0000' + CAST(ISNULL(TRY_CAST(NULLIF(LTRIM(RTRIM([번])), N'') AS INT), 0) AS NVARCHAR(10)), 4) + RIGHT(N'0000' + CAST(ISNULL(TRY_CAST(NULLIF(LTRIM(RTRIM([지])), N'') AS INT), 0) AS NVARCHAR(10)), 4) AS CHAR(19)) END AS [pnu],
       CAST(NULLIF(LTRIM(RTRIM([시군구_코드])), N'') AS CHAR(5)) AS [sigungu_cd],
       CAST(NULLIF(LTRIM(RTRIM([법정동_코드])), N'') AS CHAR(5)) AS [bjdong_cd],
       CAST(NULLIF(LTRIM(RTRIM([대지_구분_코드])), N'') AS VARCHAR(1)) AS [plat_gb_cd],
       CAST(NULLIF(LTRIM(RTRIM([번])), N'') AS VARCHAR(10)) AS [bun],
       CAST(NULLIF(LTRIM(RTRIM([지])), N'') AS VARCHAR(10)) AS [ji],
       CAST(NULLIF(LTRIM(RTRIM([대지_위치])), N'') AS NVARCHAR(300)) AS [plat_plc],
       CAST(NULLIF(LTRIM(RTRIM([건물_명])), N'') AS NVARCHAR(200)) AS [bld_nm],
       CAST(NULLIF(LTRIM(RTRIM([특수지_명])), N'') AS NVARCHAR(100)) AS [splot_nm],
       CAST(NULLIF(LTRIM(RTRIM([블록])), N'') AS NVARCHAR(40)) AS [block],
       CAST(NULLIF(LTRIM(RTRIM([로트])), N'') AS NVARCHAR(40)) AS [lot],
       CAST(NULLIF(LTRIM(RTRIM([지목_코드])), N'') AS VARCHAR(10)) AS [jimok_cd],
       CAST(NULLIF(LTRIM(RTRIM([지목_코드_명])), N'') AS NVARCHAR(40)) AS [jimok_nm],
       CAST(NULLIF(LTRIM(RTRIM([지역_코드])), N'') AS VARCHAR(10)) AS [jiyuk_cd],
       CAST(NULLIF(LTRIM(RTRIM([지역_코드_명])), N'') AS NVARCHAR(80)) AS [jiyuk_nm],
       CAST(NULLIF(LTRIM(RTRIM([지구_코드])), N'') AS VARCHAR(10)) AS [jigu_cd],
       CAST(NULLIF(LTRIM(RTRIM([지구_코드_명])), N'') AS NVARCHAR(80)) AS [jigu_nm],
       CAST(NULLIF(LTRIM(RTRIM([구역_코드])), N'') AS VARCHAR(10)) AS [guyuk_cd],
       CAST(NULLIF(LTRIM(RTRIM([구역_코드_명])), N'') AS NVARCHAR(80)) AS [guyuk_nm],
       CAST(NULLIF(LTRIM(RTRIM([건축_구분_코드])), N'') AS VARCHAR(10)) AS [arch_gb_cd],
       CAST(NULLIF(LTRIM(RTRIM([건축_구분_코드_명])), N'') AS NVARCHAR(40)) AS [arch_gb_nm],
       CAST(NULLIF(LTRIM(RTRIM([주_용도_코드])), N'') AS VARCHAR(10)) AS [main_purps_cd],
       CAST(NULLIF(LTRIM(RTRIM([주_용도_코드_명])), N'') AS NVARCHAR(80)) AS [main_purps_nm],
       TRY_CONVERT(DECIMAL(18, 4), TRY_CONVERT(FLOAT, NULLIF(LTRIM(RTRIM([대지_면적])), N''))) AS [plat_area],
       TRY_CONVERT(DECIMAL(18, 4), TRY_CONVERT(FLOAT, NULLIF(LTRIM(RTRIM([건축_면적])), N''))) AS [arch_area],
       TRY_CONVERT(DECIMAL(14, 5), TRY_CONVERT(FLOAT, NULLIF(LTRIM(RTRIM([건폐_율])), N''))) AS [bc_rat],
       TRY_CONVERT(DECIMAL(18, 4), TRY_CONVERT(FLOAT, NULLIF(LTRIM(RTRIM([연면적])), N''))) AS [tot_area],
       TRY_CONVERT(DECIMAL(18, 4), TRY_CONVERT(FLOAT, NULLIF(LTRIM(RTRIM([용적_률_산정_연면적])), N''))) AS [vl_rat_estm_tot_area],
       TRY_CONVERT(DECIMAL(14, 5), TRY_CONVERT(FLOAT, NULLIF(LTRIM(RTRIM([용적_률])), N''))) AS [vl_rat],
       TRY_CONVERT(INT, TRY_CONVERT(DECIMAL(38, 9), NULLIF(LTRIM(RTRIM([주_건축물_수])), N''))) AS [main_bld_cnt],
       TRY_CONVERT(INT, TRY_CONVERT(DECIMAL(38, 9), NULLIF(LTRIM(RTRIM([부속_건축물_동_수])), N''))) AS [atch_bld_dong_cnt],
       TRY_CONVERT(INT, TRY_CONVERT(DECIMAL(38, 9), NULLIF(LTRIM(RTRIM([세대_수])), N''))) AS [hhld_cnt],
       TRY_CONVERT(INT, TRY_CONVERT(DECIMAL(38, 9), NULLIF(LTRIM(RTRIM([호_수])), N''))) AS [ho_cnt],
       TRY_CONVERT(INT, TRY_CONVERT(DECIMAL(38, 9), NULLIF(LTRIM(RTRIM([가구_수])), N''))) AS [fmly_cnt],
       TRY_CONVERT(INT, TRY_CONVERT(DECIMAL(38, 9), NULLIF(LTRIM(RTRIM([총_주차_수])), N''))) AS [tot_pkng_cnt],
       CAST(NULLIF(LTRIM(RTRIM([건축_허가_일])), N'') AS CHAR(8)) AS [arch_pms_day],
       CAST(NULLIF(LTRIM(RTRIM([착공_예정_일])), N'') AS CHAR(8)) AS [stcns_sched_day],
       CAST(NULLIF(LTRIM(RTRIM([실제_착공_일])), N'') AS CHAR(8)) AS [real_stcns_day],
       CAST(NULLIF(LTRIM(RTRIM([착공_연기_일])), N'') AS CHAR(8)) AS [stcns_delay_day],
       CAST(NULLIF(LTRIM(RTRIM([사용승인_일])), N'') AS CHAR(8)) AS [use_apr_day],
       CAST(NULLIF(LTRIM(RTRIM([생성_일자])), N'') AS CHAR(8)) AS [crtn_day],
       CAST('HUB_0101' AS VARCHAR(30)) AS [src],
       [행해시] AS [row_hash],
       CAST(NULL AS BIGINT) AS [src_run_id],
       CAST(CAST([처음월] + '01' AS DATE) AS DATETIME2(0)) AS [valid_from],
       CAST('9999-12-31' AS DATETIME2(0)) AS [valid_to],
       CAST(1 AS BIT) AS [is_current]
  FROM hub.t0101
 WHERE [마지막월] IS NULL;
GO
