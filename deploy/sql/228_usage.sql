/* ============================================================
   228_usage : 이용현황을 담을 표 (2026-10-20)

   사용자 요청: 홈 / 지도 / 이용현황 3탭. 이용현황은 **모두에게 공개**한다.

   ★ 무엇을 담나 — **횟수만** 담는다.
     IP 도, 로그인한 사람도, 검색어도 담지 않는다. 담으면 지켜야 할 것이 생기고,
     공공데이터로 만든 비상업 서비스에 그런 것을 둘 이유가 없다.
     담는 것은 '어떤 동작이 몇 시에 몇 번' 이 전부다.

   ★ 왜 시(時) 단위로 접나 — 요청마다 한 줄씩 쌓으면 금방 수백만 줄이 되고,
     그걸 매번 세면 화면이 느려진다. 처음부터 접어서 넣으면 하루 24줄 x 동작 수다.
     1년을 쌓아도 15만 줄이 안 된다.

   ★ 시각은 **한국 시간**을 시 단위로 내린 값이다(화면이 한국 사람용이다).
     서버(Node)에서 계산해서 넣는다 — DB 의 시간대 설정에 기대지 않는다.

   ★ PK 를 (시각, 동작) 순서로 둔다. 조회가 늘 '언제부터 언제까지' 로 좁힌 뒤
     동작별로 묶기 때문이다. 시각이 앞에 와야 그 좁히기가 인덱스를 탄다.
   ============================================================ */
USE Teomoony;
GO
IF SCHEMA_ID('ops') IS NULL EXEC('CREATE SCHEMA ops');
GO
IF OBJECT_ID('ops.usage_hour') IS NULL
CREATE TABLE ops.usage_hour (
    시각 DATETIME2(0)  NOT NULL,
    동작 NVARCHAR(40)  NOT NULL,
    횟수 INT           NOT NULL,
    CONSTRAINT pk_usage_hour PRIMARY KEY CLUSTERED (시각, 동작)
);
GO
PRINT '--- 확인 ---';
SELECT 줄 = COUNT(*), 가장이른 = MIN(시각), 가장늦은 = MAX(시각) FROM ops.usage_hour;
GO
