/* ★ 덮인 비율 — 등록 안 된 이름이 몇 건이나 남는지 **반드시 본다**.
   많이 남으면 표가 모자란 것이고, 그건 화면에 '분류 못 함' 으로 나간다. */
PRINT '--- 덮인 비율 (bld_jijigu 의 용도지역 행 기준) ---';
SELECT 전체행 = COUNT(*),
       등록됨 = SUM(CASE WHEN l.jijigu_nm IS NOT NULL THEN 1 ELSE 0 END),
       미등록 = SUM(CASE WHEN l.jijigu_nm IS NULL THEN 1 ELSE 0 END),
       이름이NULL = SUM(CASE WHEN j.jijigu_nm IS NULL THEN 1 ELSE 0 END)
  FROM silver.bld_jijigu j
  LEFT JOIN meta.jijigu_level l ON l.jijigu_nm = j.jijigu_nm
 WHERE j.is_current = 1 AND j.jijigu_gb_cd = '1';
GO

PRINT '--- 아직 등록 안 된 이름 (많은 순 15개) ---';
SELECT TOP 15 j.jijigu_nm, 건수 = COUNT(*)
  FROM silver.bld_jijigu j
  LEFT JOIN meta.jijigu_level l ON l.jijigu_nm = j.jijigu_nm
 WHERE j.is_current = 1 AND j.jijigu_gb_cd = '1' AND l.jijigu_nm IS NULL
 GROUP BY j.jijigu_nm ORDER BY COUNT(*) DESC;
GO
